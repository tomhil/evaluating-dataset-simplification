"""REPORT.md: the tables of one run, generated. Interpretation lives in
analysis/FINDINGS.md, written against these tables."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from . import catalog as cat

SYM = {"up": "↑", "down": "↓", "equiv": "≈", "unclear": "?", "na": "–"}
ORDER = sorted(cat.LABELLED, key=lambda c: (["biomedical", "legal", "encyclopedia", "news"].index(cat.DOMAIN_OF[c]),
                                            cat.FAMILY[c] == "SUM", cat.LABELLED.index(c)))


def _fmt(v, nd=3):
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "no"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return "–" if not np.isfinite(v) else f"{v:.{nd}f}"
    return str(v)


def md_table(df: pd.DataFrame, nd=3) -> str:
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    body = ["| " + " | ".join(_fmt(v, nd) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def s1_summary(t4: pd.DataFrame, t1: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Features in the three views that enter S1: all 13 corpora, not a length
    proxy, and (for level views) not model-based."""

    proxy = set(t1.loc[t1["length_proxy"] == True, "metric"])  # noqa: E712
    a = t4[(t4["view"] != "pair") & (t4["n_corpora"] == len(cat.LABELLED)) & ~t4["metric"].isin(proxy)
           & ~t4["model_based_level"]].copy()
    rows = []
    seed_cols = [c for c in a.columns if c.startswith("omega2_task_s")]
    for view in ("source", "target", "delta"):
        g = a[a["view"] == view]
        row = {"view": view, "features": len(g),
               "task ω² > domain ω²": int((g["omega2_task"] > g["omega2_domain"]).sum())}
        if seed_cols:
            sfx = seed_cols[0].split("omega2_task")[1]
            row[f"same, seed {sfx[2:]}"] = int((g[f"omega2_task{sfx}"] > g[f"omega2_domain{sfx}"]).sum())
            row["seed-stable features"] = int(g["seed_stable"].sum())
            gs = g[g["seed_stable"]]
            row["task > domain, seed-stable only"] = int((gs["omega2_task"] > gs["omega2_domain"]).sum())
        rows.append({**row,
                     "median ω² task": g["omega2_task"].median(), "median ω² domain": g["omega2_domain"].median(),
                     "task p ≤ 0.05": int((g["p"] <= 0.05).sum()), "domain p ≤ 0.05": int((g["p_domain"] <= 0.05).sum()),
                     "median R² task": g["r2_task_given_domain"].median(),
                     "median R² domain": g["r2_domain_given_task"].median()})
    return pd.DataFrame(rows), a


def write(res: dict, out: Path) -> None:
    t1, t2, t3, t4 = res["t1"], res["t2"], res["t3"], res["t4"]
    sig, s = res["sigma"], res["settings"]
    L = ["# Cross-corpus comparison: tables", "",
         f"Generated by `python -m analysis.run` (seed {s.seed}, {s.repeats} resampling repeats per distance "
         f"matrix, {s.domain_perms} domain permutations, {s.boot} bootstrap replicates). Plan: "
         "`docs/analysis-plan.md`. Interpretation: `analysis/FINDINGS.md`. No metric was recomputed: the inputs "
         "are the existing `per_pair.parquet` files.", ""]

    # 1. data and gates ---------------------------------------------------
    g, cons, inv = res["gate"], res["consistency"], res["inventory"]
    L += ["## 1. Data and gates", "",
          f"- Runs read: {int(inv['per_pair'].sum())} of {len(inv)} expected run directories present "
          f"({int((inv['kind'] == 'base').sum())} base, {int((inv['kind'] == 'later').sum())} later).",
          f"- Reproduction gate: {int(g['ok'].sum())} of {len(g)} checks pass (mean, median and n recomputed from "
          f"per-pair rows against the statistics written by the same run; sources: "
          f"{', '.join(sorted({x.split('/')[0] for x in g['source']}))}).",
          f"- Base vs later runs: {int((cons['status'] == 'identical').sum())} of {len(cons)} analysed columns "
          "shared by both runs are identical on every shared pair.",
          f"- Identities: max |coverage + novel_1gram − 1| = {res['ident']['max|coverage+novel1-1|'].max():.1e}; "
          f"M7 copies of M3 differ by at most "
          f"{max(res['ident']['max|m7 syllables - m3b|'].max(), res['ident']['max|m7 fkgl - m3a|'].max()):.1e}.",
          f"- Within-domain relabelings for the two-family test: "
          f"{int(t3.loc[t3['confirmatory'], 'n_labelings'].max())} (smallest attainable p = "
          f"{1 / t3.loc[t3['confirmatory'], 'n_labelings'].max():.3f}).", ""]
    n = pd.DataFrame([{"corpus": c, "task": cat.TASK3.get(c, "–"), "domain": cat.DOMAIN_OF.get(c, "–"),
                       "pairs": len(res["frames"][c]),
                       "base sample": int(res["frames"][c]["m8_bertscore_f1"].notna().sum())
                       if "m8_bertscore_f1" in res["frames"][c] else 0,
                       "later-run sample": int(res["frames"][c]["doc_summac_precision"].notna().sum())
                       if "doc_summac_precision" in res["frames"][c] else 0,
                       "base run": cat.BASE_RUNS[c]} for c in ORDER + cat.EXTRA])
    L += [md_table(n), ""]

    # 2. metric structure ---------------------------------------------------
    fam = t1[t1.groupby("family")["metric"].transform("size") > 1]
    L += ["## 2. Metric structure", "",
          "Redundancy families (mean within-corpus |ρ| ≥ 0.8) with more than one member; the first metric in "
          "registry order represents the family in multi-metric summaries:", "",
          md_table(fam.groupby("representative")["metric"].apply(lambda x: ", ".join(x)).reset_index()
                   .rename(columns={"metric": "members"})), "",
          "Length screen (median |ρ| with log length across corpora; length proxy at ≥ 0.5), model-based level "
          "flag, and dose-response (median ρ between a pair's Δ and its log compression):", "",
          md_table(t1[t1["rho_len_source"].notna()][["metric", "module", "sigma", "rho_len_source",
                                                     "rho_len_target", "length_proxy", "model_based_level",
                                                     "dose_response_rho"]]), ""]

    # 3. controls -------------------------------------------------------------
    h = res["halves"]["agreement"].value_counts()
    one = t2[(t2["corpus"] == "onestop") & t2["feature"].isin(["mean_sent_len", "fkgl"])]
    pc = res["positive"]
    pair4 = t4[t4["view"] == "pair"].set_index("metric")
    L += ["## 3. Controls", "",
          f"- **Split-half** (each corpus cut in two at random, every full-corpus feature): "
          f"{int(h.get('same', 0))} same outcome, {int(h.get('one unclear', 0))} one half unclear, "
          f"{int(h.get('contradictory', 0))} contradictory.",
          "- **OneStopEnglish** (teacher rewrites to a lower level): " + "; ".join(
              f"{r.feature} {SYM[r.outcome]} ({r.std_hl:+.2f} SD)" for r in one.itertuples()) + ".",
          f"- **XSum vs CNN/DailyMail novel bigrams** (expectation from Narayan et al. 2018: 83.45% vs 54.33% "
          f"CNN / 53.78% DailyMail): mean {pc['mean_a']:.3f} vs {pc['mean_b']:.3f}, medians {pc['median_a']:.3f} vs "
          f"{pc['median_b']:.3f}, A(XSum > CNN/DM) = {pc['a12']:.3f} (pass at ≥ {pc['a12_min']}): "
          f"**{'pass' if pc['pass'] else 'FAIL'}**. Novel unigrams (1 − coverage): {pc['novel_1gram_mean_a']:.3f} vs "
          f"{pc['novel_1gram_mean_b']:.3f} (published 35.76% vs 16.75% / 17.03%). Distance on novel_2gram: "
          f"{pair4.loc['novel_2gram', 'xsum_cnndm']:.2f} SD, rank {int(pair4.loc['novel_2gram', 'xsum_cnndm_rank'])} "
          f"of {int(pair4.loc['novel_2gram', 'n_pairs'])} corpus pairs (78 = farthest).",
          "- **Descriptive pairs** (no pass/fail): D-Wikipedia vs SWiPE and SWiPE-gold vs SWiPE, below. The plan-v2 "
          "expectation for SWiPE-gold rested on a corpus-level ratio against the full SWiPE corpus, not on these "
          "samples (plan v3, 5).", "",
          "Distances in suite SD units (floor = a corpus against an independent resample of itself at the common n):",
          "", md_table(t4[t4["view"] == "pair"][["metric", "n_common", "floor_rms", "between_rms", "dwiki_swipe",
                                                  "dwiki_swipe_rank", "xsum_cnndm", "xsum_cnndm_rank", "n_pairs",
                                                  "swipe_vs_gold"]]), ""]
    for key, p in res["profiles"].items():
        L += [f"- Profile `{key}`: D-Wikipedia vs SWiPE is rank {p['dwiki_swipe_rank']} of {p['n_pairs']} corpus "
              f"pairs (1 = closest); {len(p['used'])} metrics in the profile."]
    L += [""]

    # 4. pre-specified family -------------------------------------------------
    conf = t3[t3["confirmatory"]].copy()
    ids = {(n_, k): (p, sgn) for p, n_, k, sgn in cat.CONFIRMATORY}
    conf["id"] = [ids[(m, k)][0] for m, k in zip(conf["metric"], conf["kind"])]
    conf["expected"] = ["> 0" if ids[(m, k)][1] > 0 else "< 0" for m, k in zip(conf["metric"], conf["kind"])]
    conf["CI (SD)"] = [f"[{lo / sig[m]:+.2f}, {hi / sig[m]:+.2f}]" for lo, hi, m in
                       zip(conf["theta_lo"], conf["theta_hi"], conf["metric"])]
    for d in ("biomedical", "legal", "encyclopedia", "news"):
        conf[d] = [v / sig[m] for v, m in zip(conf[f"contrast_{d}"], conf["metric"])]
    conf = conf.sort_values("id")
    L += ["## 4. Pre-specified family P1–P4 (Holm, α = 0.05)", "",
          "θ = equal-weight mean over the four domains of (simplification − summarization), in suite SD units. "
          "CI: bootstrap over pairs within corpora (sampling error only, not between-corpus spread). p: exact, "
          "two-sided, task labels permuted within domain. The hypotheses were suggested by RESULTS.md on these "
          "corpora, so this is a test under a stricter null, not independent confirmation.", "",
          md_table(conf[["id", "metric", "expected", "theta_std", "CI (SD)", "biomedical", "legal", "encyclopedia",
                         "news", "domains_agree", "p_exact", "rank", "n_labelings", "p_holm"]]), "",
          "Robustness (raw units):", "",
          md_table(conf[["id", "metric", "theta", "loo_sign_stable", "loo_min", "loo_max", "theta_no_subdoc",
                         "p_no_subdoc", "n_labelings_no_subdoc"]], 4), "",
          "Relabelings with |θ| at least as large as observed, each named by the corpora it calls SUM (the observed "
          "labeling is always one of them):", ""]
    for pid, labs in res["beating"].items():
        L += [f"- {pid} ({len(labs)}): " + "; ".join("{" + ", ".join(x) + "}" for x in labs)]
    L += ["", "Family summaries, raw units (PI = 95% prediction interval for a new corpus of the family; "
          "UK-Abs shown for location only):", "",
          md_table(conf[["id", "metric", "SIMP_k", "SIMP_mean", "SIMP_pi_lo", "SIMP_pi_hi", "SUM_k", "SUM_mean",
                         "SUM_pi_lo", "SUM_pi_hi", "PLS_mean", "DS_mean", "ukabs"]]), ""]

    # 5. exploratory -----------------------------------------------------------
    ex = t3[~t3["confirmatory"] & t3["kind"].isin(["paired", "pair", "target-only"])].copy()
    ex["flags"] = [", ".join(x for x in (("length proxy" if lp is True else ""),
                                         ("post hoc" if m in cat.POST_HOC else ""),
                                         ("partial coverage" if nc < len(cat.LABELLED) else "")) if x)
                   for lp, m, nc in zip(ex["length_proxy"], ex["metric"], ex["n_corpora"])]
    m_bh = int(t3["q_BH"].notna().sum())
    k_bh = int(np.ceil((1 / 90) * m_bh / 0.05 - 1e-12)) if m_bh else 0
    ex["SIMP n↑/n↓"] = [f"{_fmt(a, 0)}/{_fmt(b, 0)}" for a, b in zip(ex["SIMP_n_up"], ex["SIMP_n_down"])]
    ex["SUM n↑/n↓"] = [f"{_fmt(a, 0)}/{_fmt(b, 0)}" for a, b in zip(ex["SUM_n_up"], ex["SUM_n_down"])]
    L += ["## 5. Exploratory task contrasts", "",
          f"Same statistic and test for every other metric. q: Benjamini–Hochberg over the {m_bh} metrics with all "
          f"13 corpora; with a smallest attainable p of 1/90, no q can fall below 0.05 unless at least {k_bh} of them "
          "reach that minimum. n↑/n↓: partial-conjunction lower bound on the number of corpora in the family whose "
          "change exceeds the SESOI in that direction (paired features).", "",
          md_table(ex.sort_values(["p_exact", "metric"])[["metric", "kind", "theta_std", "domains_agree", "p_exact",
                                                          "rank", "n_labelings", "q_BH", "loo_sign_stable",
                                                          "SIMP n↑/n↓", "SUM n↑/n↓", "n_corpora", "flags"]]), ""]

    # 6. outcome matrix ----------------------------------------------------------
    piv = t2.assign(o=[("·" if st_ else SYM[o]) for o, st_ in zip(t2["outcome"], t2["structural"])]).pivot(
        index="feature", columns="corpus", values="o")
    cols = [c for c in ORDER + cat.EXTRA if c in piv.columns]
    piv = piv.reindex(index=[f.name for f in cat.PAIRED], columns=cols).fillna("–").reset_index()
    L += ["## 6. Paired outcomes per corpus", "",
          "↑ / ↓: the 90% CI of the Hodges–Lehmann change lies beyond ±0.1 SD. ≈: inside. ?: undecided. "
          "·: fewer than 80% of pairs defined. –: not computed for that corpus.", "", md_table(piv), ""]

    # 7. oracle supplement -------------------------------------------------------
    os_ = res["osyn"]
    L += ["## 7. Supplement: selection versus rewriting (word-level measures only)", "",
          "Uses the extractive-oracle columns of the base batch (M3c, removed from the profiler on 2026-10-27): "
          "whole source sentences chosen greedily by ROUGE-1+2 recall gain against the target until the selection "
          "reaches the target's token budget. selection = oracle − source; rewriting = target − oracle.", "",
          md_table(os_[os_["interpretable"]].sort_values(["metric", "kind"])[
              ["metric", "kind", "theta_std", "domains_agree", "p_exact", "rank", "loo_sign_stable",
               "SIMP_outcomes", "SUM_outcomes"]]), "",
          "**Why the sentence-level measures are excluded.** The recall gain is not normalised by sentence length, "
          "so the oracle prefers long sentences, and it stops only after passing the budget. The words-per-sentence "
          "change implied by ΔFKGL and Δsyllables (validated on target − source against M1's measured change) shows "
          "how far the oracle's sentences exceed the source's:", "",
          md_table(res["oracle_diag"]), ""]

    # 8. distributions -------------------------------------------------------------
    b = t4[t4["view"] == "pair"]
    L += ["## 8. Distributions of pair-level metrics", "",
          "Squared 2-Wasserstein distances between corpora (debiased, suite SD units) partitioned by the additive "
          "model 1 + domain + task. ω²: partial omega squared, comparable across the 1-df task and 3-df domain "
          "factors (partial R² is not: it grows with degrees of freedom). p: exact, task relabeled within domain. "
          "p_domain: Monte Carlo, domain relabeled within task family. Shares: location / scale / shape split of "
          "the squared distances. disp: root-mean-square distance between corpora of one class.", "",
          md_table(b[[c for c in ["metric", "n_corpora", "n_common", "omega2_task", "omega2_domain", "p", "q_BH",
                                  "p_domain", f"p_s{res.get('stability_seed')}", "seed_stable",
                                  "r2_task_given_domain", "r2_domain_given_task", "share_location", "share_scale",
                                  "share_shape", "disp_PLS", "disp_DS", "disp_SUM"] if c in b.columns]]), ""]

    # 9. S1 --------------------------------------------------------------------------
    s1, a = s1_summary(t4, t1)
    L += ["## 9. Structural expectation S1: what organises the paired features in each view", "",
          "Features with all 13 corpora that are not length proxies; model-based features are left out of the "
          "two level views (plan 4.4). Counts are descriptive: the features are not independent.", "",
          md_table(s1), "", "Per feature (ω²):", "",
          md_table(a.pivot(index="metric", columns="view", values=["omega2_task", "omega2_domain"])
                   .pipe(lambda d: d.set_axis([f"{'task' if 'task' in x else 'domain'} ω², {v}" for x, v in d.columns],
                                              axis=1)).reset_index()), ""]
    for key, p in res["profiles"].items():
        vp = p["partition"]
        other = res.get("stability", {}).get("profiles", {}).get(key)
        extra = (f" Seed {res['stability_seed']}: task ω² {other['omega2_task'][1]:.3f}, domain ω² "
                 f"{other['omega2_domain'][1]:.3f}, p (task) {other['p'][1]:.3f}, p (domain) {other['p_domain'][1]:.4f}."
                 if other else "")
        L += [f"- Profile `{key}` ({len(p['used'])} metrics): task ω² = {vp['omega2_task']:.3f}, domain ω² = "
              f"{vp['omega2_domain']:.3f}; exact p (task) = {vp['p']:.3f} over {vp['n_labelings']} labelings; "
              f"p (domain) = {vp['p_domain']:.4f} over {vp['domain_perms']} permutations.{extra}"]
    L += [""]

    # 10. sensitivity and stability -------------------------------------------------
    L += ["## 10. Sensitivity and stability", "",
          "Outcome counts over the labelled corpora, and replicability counts for the paired pre-specified "
          "features, by SESOI (SD units):", "", md_table(res["sesoi"], 2), ""]
    if "stability" in res:
        L += [f"Recomputed with seed {res['stability_seed']} (held in memory; the tables above are seed "
              f"{s.seed}). Deterministic quantities must be identical; distance-based ones are reported for both "
              "seeds in T4, where `seed_stable` marks rows whose p, p_domain and ω² move by at most 0.05 and keep "
              "their task-vs-domain ordering. Claims rest on seed-stable rows only.", ""]
        L += [f"- {k}: {_fmt(v, 4)}" for k, v in res["stability"].items() if k != "profiles"]
        t4s = t4[t4["seed_stable"].notna()] if "seed_stable" in t4 else t4.iloc[0:0]
        if len(t4s):
            L += [f"- seed-stable T4 rows: {int(t4s['seed_stable'].sum())} of {len(t4s)}"]
        L += [""]
    L += ["## Figures", "", "![effect matrix](fig1_effect_matrix.png)", "",
          "![pre-specified contrasts](fig2_confirmatory_forest.png)", "",
          "![variance partition](fig3_variance_partition.png)", "", "![profile MDS](fig4_profile_mds.png)", "",
          "![selection versus rewriting](fig5_selection_vs_rewriting.png)", ""]
    (out / "REPORT.md").write_text("\n".join(L), encoding="utf-8")
