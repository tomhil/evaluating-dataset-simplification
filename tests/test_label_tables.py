def test_part1_layout(inline_results):
    text = lt.render(inline_results)
    sum_table = text.split("#### SUM — summarization metrics")[1].split("####")[0]
    lines = [l for l in sum_table.splitlines() if l.startswith("|")]
    assert lines[0] == "| Metric | cochrane | plos | contracts | xsum | billsum |"
    assert lines[2] == "| *dataset task* | PLS | PLS | PLS | SUM | SUM |"
    coverage = next(l for l in lines if "[Coverage]" in l)
    assert coverage.endswith("↑ more copied | 0.704 | 0.913 | 0.500 | 0.650 | 0.906 |")
    # A metric that is empty everywhere collapses into the "not yet computed" line.
    assert "[Density]" not in sum_table
    assert "Not yet computed for any dataset:" in sum_table and "Density" in sum_table
    ds_table = text.split("#### DS — document simplification metrics")[1].split("###")[0]
    fkgl = next(l for l in ds_table.splitlines() if "[FKGL]" in l)
    assert f"| 12.6 (Δ {MINUS}1.60) |" in fkgl and "| 20.7 (Δ 0.00) |" in fkgl
    bleu = next(l for l in ds_table.splitlines() if "BLEU(target, source)" in l)
    assert "BLEU(target, source)](docs/metrics.md#pair_similaritybleu--bleutarget-source)† ↑ closer to source wording" in bleu
    assert bleu.endswith("| 11.9 | — | — | 0.00 | 0.0184 |")


