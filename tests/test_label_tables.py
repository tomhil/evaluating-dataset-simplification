def test_only_multi_task_domains_get_tables(inline_results):
    # The inline biomedical datasets (cochrane, plos) are both PLS.
    multi, single = lt.split_domains(inline_results)
    assert multi == ["legal"]
    assert single == [("biomedical", ["PLS"]), ("news", ["SUM"])]
    text = lt.render(inline_results)
    assert "#### Legal" in text and "#### Biomedical" not in text and "#### News" not in text
    assert "biomedical (PLS only) and news (SUM only) have a single task label" in text
    legal = text.split("#### Legal")[1]
    rows = [l for l in legal.splitlines() if l.startswith("|")]
    assert rows[0] == "| Metric | contracts | billsum |"
    assert rows[2] == "| *dataset task* | PLS | SUM |"
    assert rows[3] == "| **SUM metrics** |  |  |"
    assert any(r.startswith("| **PLS metrics**") for r in rows)


