# Staleness
# --------------------------------------------------------------------------
def test_check_detects_a_stale_block(tmp_path, inline_results):
    block = lt.render(inline_results)
    doc = tmp_path / "RESULTS.md"
    doc.write_text("# Results\n\n" + block + "\n## M1 — Length and compression\n")
    results_dir = tmp_path / "res"
    results_dir.mkdir()
    for p in tmp_path.glob("*.json"):
        p.rename(results_dir / p.name)
    assert lt.main(["--check", str(doc), "--results", str(results_dir)]) == 0
    doc.write_text(doc.read_text().replace("0.704", "0.705"))
    assert lt.main(["--check", str(doc), "--results", str(results_dir)]) == 1
    assert lt.main(["--write", str(doc), "--results", str(results_dir)]) == 0
    assert lt.main(["--check", str(doc), "--results", str(results_dir)]) == 0


