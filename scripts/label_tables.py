# --------------------------------------------------------------------------
# Formatting (PRD s5.7)
# --------------------------------------------------------------------------
def _neg(s: str, negative: bool) -> str:
    return f"{MINUS}{s}" if negative else s


def fmt_value(x, fmt: str = "sig3") -> str:
    """Three significant figures with trailing zeros; counts as whole numbers;
    non-zero values below 0.001 as <0.001; missing as a dash; U+2212 minus."""

    if x is None or (isinstance(x, float) and math.isnan(x)):
        return EMPTY
    x = float(x)
    if fmt == "int":
        n = int(round(x))
        return _neg(str(abs(n)), n < 0)
    if x == 0:
        return "0.00"
    if abs(x) < 0.001:
        return "<0.001" if x > 0 else f">{MINUS}0.001"
    r = float(f"{abs(x):.3g}")
    digits = max(0, 2 - math.floor(math.log10(r)))
    return _neg(f"{r:.{digits}f}", x < 0)


def fmt_delta(x) -> str:
    """Always signed, two decimals; exactly zero (after rounding) is 0.00."""

    if x is None:
        return EMPTY
    d = round(float(x), 2)
    if d == 0:
        return "0.00"
    return ("+" if d > 0 else MINUS) + f"{abs(d):.2f}"


# --------------------------------------------------------------------------
# Reading results
# --------------------------------------------------------------------------
def _get(node, dotted: str):
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    return node


def metric_node(result: dict, key: str):
    module, rest = key.split(".", 1)
    return _get(result.get("modules", {}).get(module, {}).get("corpus", {}), rest)


def cell(result: dict, m: MetricLabel) -> str:
    node = metric_node(result, m.key)
    if node is None:
        return EMPTY
    if m.headline == ():
        return fmt_value(node if not isinstance(node, dict) else None, m.fmt)
    if m.headline == ("target.median", "delta.median"):
        target = _get(node, "target.median")
        if target is None:
            return EMPTY
        delta = _get(node, "delta.median")
        return fmt_value(target, m.fmt) + ("" if delta is None else f" (Δ {fmt_delta(delta)})")
    values = [_get(node, h) for h in m.headline]
    if all(v is None for v in values):
        return EMPTY
    return " / ".join(fmt_value(v, m.fmt) for v in values)


def load_results(results_dir: Path) -> dict[str, dict]:
    """Datasets in ORDER that have a results file, in Part 1 column order."""

    found = {p.stem: json.loads(p.read_text()) for p in sorted(results_dir.glob("*.json"))}
    shown = [d for d in ORDER if d in found]
    shown.sort(key=lambda d: TASK_RANK[TASK[d]])  # stable: keeps ORDER within a task
    return {d: found[d] for d in shown}


