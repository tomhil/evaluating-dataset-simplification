"""Generate the "Datasets by metric label" section of RESULTS.md.

Compares every profiled dataset on the metrics of each label group (SUM, PLS,
DS): across all datasets, and within each domain that has more than one task.
Every number comes from ``results/*.json`` through the metric registry; nothing
here is typed by hand.

    python scripts/label_tables.py                       # print the markdown
    python scripts/label_tables.py --write RESULTS.md    # replace the block between the markers
    python scripts/label_tables.py --check RESULTS.md    # exit 1 if the block is stale

Same inputs give byte-identical output: no timestamps, fixed orders.
"""

