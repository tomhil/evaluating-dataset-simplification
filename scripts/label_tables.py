# Rendering
# --------------------------------------------------------------------------
def _labelled(task: str) -> list[MetricLabel]:
    order = {m.key: i for i, m in enumerate(REGISTRY)}
    rows = [m for m in REGISTRY if task in m.tasks]
    return sorted(rows, key=lambda m: (m.module, order[m.key]))


def row_label(m: MetricLabel, anchors: dict[str, str]) -> str:
    dagger = "†" if m.sample_based else ""
    direction = f" {m.direction}" if m.direction else ""
    return f"[{NAMES[m.key]}](docs/metrics.md#{anchors[m.key]}){dagger}{direction}"


def _join(names: list[str]) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _task_row(datasets: list[str]) -> list[str]:
    return ["*dataset task*"] + [TASK[d] for d in datasets]


def part1(results: dict[str, dict], anchors: dict[str, str]) -> list[str]:
    datasets = list(results)
    out: list[str] = []
    for task, title in GROUPS:
        rows, empty = [], []
        for m in _labelled(task):
            cells = [cell(results[d], m) for d in datasets]
            if all(c == EMPTY for c in cells):
                empty.append(NAMES[m.key])
            else:
                rows.append([row_label(m, anchors)] + cells)
        out += ["", f"#### {task} — {title}", ""]
        out += _table(["Metric"] + datasets, [_task_row(datasets)] + rows)
        if empty:
            out += ["", f"Not yet computed for any dataset: {', '.join(empty)}."]
    return out


def split_domains(results: dict[str, dict]) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """(multi-task domains, [(single-task domain, its tasks)]) in first-seen order."""

    domains: dict[str, list[str]] = {}
    for d in results:
        domains.setdefault(DOMAIN[d], []).append(d)
    multi, single = [], []
    for dom, ds in domains.items():
        tasks = sorted({TASK[d] for d in ds}, key=lambda t: TASK_RANK[t])
        (multi if len(tasks) >= 2 else single).append(dom if len(tasks) >= 2 else (dom, tasks))
    return multi, single


def part2(results: dict[str, dict], anchors: dict[str, str]) -> list[str]:
    multi, _single = split_domains(results)
    out: list[str] = []
    for dom in multi:
        datasets = [d for d in results if DOMAIN[d] == dom]
        rows = [_task_row(datasets)]
        for task, _title in GROUPS:
            group = []
            for m in _labelled(task):
                cells = [cell(results[d], m) for d in datasets]
                if any(c != EMPTY for c in cells):
                    group.append([row_label(m, anchors)] + cells)
            if group:
                rows.append([f"**{task} metrics**"] + [""] * len(datasets))
                rows += group
        out += ["", f"#### {dom.capitalize()}", ""]
        out += _table(["Metric"] + datasets, rows)
    return out


def _sizes_footnote(results: dict[str, dict]) -> str:
    def phrase(field: str) -> str:
        by_n: dict[int, list[str]] = {}
        for d, r in results.items():
            by_n.setdefault(int(r[field]), []).append(d)
        common = max(by_n, key=lambda n: (len(by_n[n]), n))
        parts = [f"{n:,} pairs for {_join(ds)}" for n, ds in sorted(by_n.items()) if n != common]
        rest = f"{common:,} for every other dataset" if parts else f"{common:,} for every dataset"
        return ", ".join(parts + [rest])

    return (
        f"† Computed on a seeded sample: {phrase('n_sample')}. "
        f"Unmarked metrics use the full corpus: {phrase('n_full')}."
    )


def render(results: dict[str, dict], anchors: dict[str, str] | None = None) -> str:
    if not results:
        raise ValueError("no results to render: no results/*.json for a dataset in ORDER")
    anchors = anchors_by_key([m.key for m in REGISTRY]) if anchors is None else anchors
    multi, single = split_domains(results)
    single_text = _join([f"{dom} ({', '.join(tasks)} only)" for dom, tasks in single]) if single else ""
    lines = [
        BEGIN,
        "## Datasets by metric label",
        "",
        "Generated by scripts/label_tables.py from results/*.json. Do not edit by hand.",
        "",
        "### Across all datasets",
        "",
        "SUM is generic summarization, PLS plain-language (lay) summarization and DS "
        "document simplification. Each table holds the metrics that task's literature "
        "uses, per [the metric reference](docs/metrics.md); a metric used for several "
        "tasks appears in each of its tables. The grouping describes metrics, not "
        "datasets: every dataset appears in every table, and the first row gives each "
        "dataset's own task. Cells are medians; for a metric measured on both sides, "
        "`target (Δ change)` gives the target's median and Δ the median of per-pair "
        "differences (target − source). Arrows give each metric's direction. "
        "Metrics marked † are computed on a seeded sample.",
    ]
    lines += part1(results, anchors)
    lines += [
        "",
        "### Within domain",
        "",
        "Here domain is held constant, so a difference between columns is not a "
        "difference of subject matter. Only domains whose datasets carry at least two "
        "task labels get a table"
        + (f"; {single_text} have a single task label, so there is nothing to compare "
           "within them." if single else ".")
        + " † and Δ mean the same as above, and metrics with no value for any dataset "
        "in a domain are omitted; the lists above name the metrics not yet computed.",
    ]
    lines += part2(results, anchors)
    lines += [
        "",
        _sizes_footnote(results),
        "",
        "The hand-written tables under \"The domain-controlled comparison\" report "
        "means, so their figures differ from the medians here.",
        END,
    ]
    return "\n".join(lines) + "\n"


def replace_block(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit("label-tables markers not found; add them once before --write")
    head, rest = text.split(BEGIN, 1)
    _old, tail = rest.split(END, 1)
    return head + block.rstrip("\n") + tail


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--write", metavar="FILE", help="replace the block between the markers")
    group.add_argument("--check", metavar="FILE", help="exit 1 if the block is stale")
    ap.add_argument("--results", default=str(_ROOT / "results"), help="directory of results/*.json")
    args = ap.parse_args(argv)

    results = load_results(Path(args.results))
    if not results:
        print(f"{args.results}: no results/*.json for any dataset in ORDER", file=sys.stderr)
        return 2
    block = render(results)
    if args.write:
        path = Path(args.write)
        path.write_text(replace_block(path.read_text(), block))
        return 0
    if args.check:
        path = Path(args.check)
        text = path.read_text()
        if replace_block(text, block) != text:
            print(f"{path}: label-tables block is stale; run --write", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
